#!/usr/local/bin/python3
"""
Tests for MontecarloSimulationDataLoader: data is loaded once and shared by all per-CPU MontecarloSimulation objects
Uses the real input files in ./Data and the settings in src/run_montecarlo_simulation.toml
"""
import sys
import tomllib
from pathlib import Path
from typing import Any

import pytest

PROJECT_DIR = Path(__file__).resolve().parent.parent
SRC_DIR = PROJECT_DIR / "src"
sys.path.insert(0, str(SRC_DIR))

from montecarlo_simulation_class import MontecarloSimulation, MontecarloSimulationDataLoader  # noqa: E402

CONFIG_FILE = SRC_DIR / "run_montecarlo_simulation.toml"
DATA_DIR = PROJECT_DIR / "Data"
NB_CPU = 3
RUN_CNT = 30


class FileConfigManager:
    """Stand-in for ConfigurationManager: reads the run config, with absolute data paths and a small run"""
    def __init__(self, cross_correlated_rvs_flag: bool) -> None:
        with open(CONFIG_FILE, "rb") as fp:
            self.full_config = tomllib.load(fp)
        self.full_config["default"].update(
            {"nb_cpu": NB_CPU, "run_cnt": RUN_CNT, "cross_correlated_rvs_flag": cross_correlated_rvs_flag}
        )

    def get_class_config(self, class_name: str) -> dict[str, Any]:
        config = dict(self.full_config.get("default", {}))
        config.update(self.full_config.get(class_name, {}))
        if "input_directory" in config:
            config["input_directory"] = str(DATA_DIR)
        return config


def make_simulations(cross_correlated_rvs_flag: bool) -> tuple[MontecarloSimulationDataLoader, list[MontecarloSimulation]]:
    config_manager = FileConfigManager(cross_correlated_rvs_flag)
    data_loader = MontecarloSimulationDataLoader(config_manager)  # type: ignore[arg-type]
    simulations = [MontecarloSimulation(config_manager, data_loader, cpu_idx) for cpu_idx in range(NB_CPU)]  # type: ignore[arg-type]
    return data_loader, simulations


@pytest.mark.parametrize("cross_correlated_rvs_flag", [False, True])
def test_data_is_loaded_once_for_all_cpus(monkeypatch: pytest.MonkeyPatch, cross_correlated_rvs_flag: bool) -> None:
    load_cnt = 0
    original_load_data = MontecarloSimulationDataLoader.load_data

    def counting_load_data(self: MontecarloSimulationDataLoader) -> None:
        nonlocal load_cnt
        load_cnt += 1
        original_load_data(self)

    monkeypatch.setattr(MontecarloSimulationDataLoader, "load_data", counting_load_data)
    make_simulations(cross_correlated_rvs_flag)

    assert load_cnt == 1


def test_all_cpus_share_the_same_loaded_data() -> None:
    _, simulations = make_simulations(cross_correlated_rvs_flag=False)

    first = simulations[0]
    for simulation in simulations[1:]:
        assert simulation.cashflow_df is first.cashflow_df
        assert simulation.rng_sequence is first.rng_sequence


def test_each_cpu_gets_its_own_correlated_ror_table() -> None:
    data_loader, simulations = make_simulations(cross_correlated_rvs_flag=True)

    # Each CPU has its own seeds: distinct branches of the master SeedSequence
    cpu_spawn_keys = [
        {rng.bit_generator.seed_seq.spawn_key for rng in data_loader.rng_sequence[simulation.cpu_idx]}  # type: ignore[attr-defined]
        for simulation in simulations
    ]
    for idx, spawn_keys in enumerate(cpu_spawn_keys[1:], start=1):
        assert spawn_keys.isdisjoint(cpu_spawn_keys[0]), f"CPU {idx} shares seeds with CPU 0"

    assert all(simulation.correlated_ror is None for simulation in simulations), "tables must be generated by the worker, not the loader"
    for simulation in simulations:
        simulation.generate_correlated_ror()
    tables = [simulation.correlated_ror for simulation in simulations]
    for table, simulation in zip(tables, simulations):
        assert table is not None
        assert table.shape[1] == simulation.run_cnt * simulation.nb_years
    for idx, table in enumerate(tables[1:], start=1):
        assert not table.equals(tables[0]), f"CPU {idx} reuses CPU 0 RoR samples"


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-v"]))
